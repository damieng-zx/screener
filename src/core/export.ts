import {
  BITMAP_BYTES,
  CELL_H,
  CELL_W,
  COLS,
  PALETTE,
  ROWS,
  SCR_BYTES,
  SCREEN_H,
  SCREEN_W,
  attributeFromByte,
  bitmapOffset,
} from './palette';
import type { ConversionResult } from './types';

/** Bit 7 of every bitmap byte is the leftmost pixel of that byte. */
export function bitmapByteAt(result: ConversionResult, y: number, col: number): number {
  const attr = attributeFromByte(result.attr[(y >> 3) * COLS + col]);
  let byte = 0;
  for (let bit = 0; bit < 8; bit++) {
    const idx = result.pixelIdx[y * SCREEN_W + col * 8 + bit];
    const p = PALETTE[idx];
    // Black exists in both halves of the palette, so it matches either way.
    const isInk = p.code === attr.ink && (p.code === 0 || p.bright === attr.bright);
    if (isInk) byte |= 0x80 >> bit;
  }
  return byte;
}

/**
 * Classic 6912-byte .scr memory image: 6144 bitmap bytes in the ULA's
 * interleaved order, then 768 attribute bytes left to right, top to bottom.
 */
export function toScr(result: ConversionResult): Uint8Array<ArrayBuffer> {
  const out = new Uint8Array(SCR_BYTES);
  for (let y = 0; y < SCREEN_H; y++) {
    for (let col = 0; col < COLS; col++) {
      out[bitmapOffset(y, col)] = bitmapByteAt(result, y, col);
    }
  }
  out.set(result.attr, BITMAP_BYTES);
  return out;
}

/**
 * Inverse of toScr, used to sanity-check the layout and to allow importing an
 * existing .scr for comparison.
 */
export function fromScr(scr: Uint8Array): {
  screen: Uint8ClampedArray<ArrayBuffer>;
  attr: Uint8Array<ArrayBuffer>;
  pixelIdx: Uint8Array<ArrayBuffer>;
} {
  if (scr.length < SCR_BYTES) throw new Error('A .scr file is 6912 bytes');
  const attr = scr.slice(BITMAP_BYTES, SCR_BYTES);
  const screen = new Uint8ClampedArray(SCREEN_W * SCREEN_H * 4);
  const pixelIdx = new Uint8Array(SCREEN_W * SCREEN_H);
  const indexOf = new Map<string, number>();
  PALETTE.forEach((p, i) => indexOf.set(`${p.code}:${p.bright}`, i));
  const lookup = (code: number, bright: boolean): number =>
    indexOf.get(`${code}:${bright}`) ?? indexOf.get(`${code}:false`) ?? 0;
  for (let y = 0; y < SCREEN_H; y++) {
    for (let col = 0; col < COLS; col++) {
      const byte = scr[bitmapOffset(y, col)];
      const a = attributeFromByte(attr[(y >> 3) * COLS + col]);
      const inkIdx = lookup(a.ink, a.bright);
      const paperIdx = lookup(a.paper, a.bright);
      for (let bit = 0; bit < 8; bit++) {
        const set = (byte & (0x80 >> bit)) !== 0;
        const p = PALETTE[set ? inkIdx : paperIdx];
        const i = y * SCREEN_W + col * 8 + bit;
        pixelIdx[i] = set ? inkIdx : paperIdx;
        screen[i * 4] = p.rgb[0];
        screen[i * 4 + 1] = p.rgb[1];
        screen[i * 4 + 2] = p.rgb[2];
        screen[i * 4 + 3] = 255;
      }
    }
  }
  return { screen, attr, pixelIdx };
}

export interface PngOptions {
  /** Integer upscale of the 256x192 buffer. */
  scale: number;
  /** Draw faint 8x8 cell borders. */
  grid: boolean;
}

/** Render the screen into a PNG data URL using a canvas. */
export async function toPng(result: ConversionResult, opt: PngOptions): Promise<Blob> {
  const small = document.createElement('canvas');
  small.width = SCREEN_W;
  small.height = SCREEN_H;
  const ctx = small.getContext('2d')!;
  const img = new ImageData(new Uint8ClampedArray(result.screen), SCREEN_W, SCREEN_H);
  ctx.putImageData(img, 0, 0);

  if (opt.grid) {
    ctx.strokeStyle = 'rgba(0,0,0,0.35)';
    ctx.lineWidth = 1;
    for (let x = 0; x <= SCREEN_W; x += CELL_W) {
      ctx.beginPath();
      ctx.moveTo(x + 0.5, 0);
      ctx.lineTo(x + 0.5, SCREEN_H);
      ctx.stroke();
    }
    for (let y = 0; y <= SCREEN_H; y += CELL_H) {
      ctx.beginPath();
      ctx.moveTo(0, y + 0.5);
      ctx.lineTo(SCREEN_W, y + 0.5);
      ctx.stroke();
    }
  }

  const scale = Math.max(1, Math.round(opt.scale));
  if (scale === 1) return toBlob(small);

  const big = document.createElement('canvas');
  big.width = SCREEN_W * scale;
  big.height = SCREEN_H * scale;
  const bctx = big.getContext('2d')!;
  bctx.imageSmoothingEnabled = false;
  bctx.drawImage(small, 0, 0, big.width, big.height);
  return toBlob(big);
}

function toBlob(canvas: HTMLCanvasElement): Promise<Blob> {
  return new Promise((resolve, reject) => {
    canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('PNG encoding failed'))), 'image/png');
  });
}

/** Emit the screen as `bytes` for a C include: bitmap then attributes. */
export function toCHeader(result: ConversionResult, name = 'screen'): string {
  const scr = toScr(result);
  const guard = `${name.toUpperCase().replace(/[^A-Z0-9]/g, '_')}_H`;
  const lines: string[] = [];
  lines.push(`/* Generated by Spectrum Screener: 256x192, 15 colours, 2 per 8x8 cell. */`);
  lines.push(`#ifndef ${guard}`);
  lines.push(`#define ${guard}`);
  lines.push('');
  lines.push(`static const unsigned char ${name}[${SCR_BYTES}] = {`);
  for (let i = 0; i < scr.length; i += 16) {
    const chunk = Array.from(scr.subarray(i, i + 16))
      .map((v) => `0x${v.toString(16).padStart(2, '0')}`)
      .join(',');
    lines.push(`  ${chunk},${i === BITMAP_BYTES ? ' /* attributes */' : ''}`);
  }
  lines.push('};');
  lines.push('');
  lines.push(`#endif /* ${guard} */`);
  lines.push('');
  return lines.join('\n');
}

/** z80 assembler include: DEFB lines in Spectrum screen order. */
export function toAsm(result: ConversionResult, label = 'screen'): string {
  const scr = toScr(result);
  const lines: string[] = [`; Generated by Spectrum Screener.`];
  lines.push(`${label}:`);
  lines.push('; --- bitmap 6144 bytes, ULA third/scanline order ---');
  for (let i = 0; i < BITMAP_BYTES; i += 8) {
    lines.push(`  defb ${Array.from(scr.subarray(i, i + 8)).map((v) => `$${v.toString(16).padStart(2, '0')}`).join(',')}`);
  }
  lines.push('; --- attributes 768 bytes ---');
  for (let i = BITMAP_BYTES; i < SCR_BYTES; i += 8) {
    lines.push(`  defb ${Array.from(scr.subarray(i, i + 8)).map((v) => `$${v.toString(16).padStart(2, '0')}`).join(',')}`);
  }
  lines.push('');
  return lines.join('\n');
}

/**
 * Build a .tap cassette image containing a single `bytes` block at 0x4000, so
 * `LOAD "" SCREEN$` on a real Spectrum (or Fuse, ZEsarUX, ...) shows the image.
 */
export function toTap(result: ConversionResult, name = 'SCREENER'): Uint8Array<ArrayBuffer> {
  const data = toScr(result);
  const header = new Uint8Array(17);
  header[0] = 3; // 3 = code / bytes block, which is what SCREEN$ loads
  const clean = name.toUpperCase().replace(/[^A-Z0-9 ]/g, '').slice(0, 10).padEnd(10, ' ');
  for (let i = 0; i < 10; i++) header[1 + i] = clean.charCodeAt(i);
  header[11] = data.length & 0xff;
  header[12] = (data.length >> 8) & 0xff;
  header[13] = 0x00; // start address 0x4000, little endian
  header[14] = 0x40;
  header[15] = 0x00; // 0x8000 = "load into memory, no autostart"
  header[16] = 0x80;

  const blocks = [wrapTapBlock(0x00, header), wrapTapBlock(0xff, data)];
  const total = blocks.reduce((n, b) => n + b.length, 0);
  const out = new Uint8Array(total);
  let o = 0;
  for (const b of blocks) {
    out.set(b, o);
    o += b.length;
  }
  return out;
}

function wrapTapBlock(flag: number, payload: Uint8Array): Uint8Array<ArrayBuffer> {
  const len = payload.length + 2; // flag + payload
  // 2 length bytes + flag + payload + checksum
  const out = new Uint8Array(len + 2);
  out[0] = len & 0xff;
  out[1] = (len >> 8) & 0xff;
  out[2] = flag;
  out.set(payload, 3);
  let checksum = flag;
  for (const b of payload) checksum ^= b;
  out[out.length - 1] = checksum;
  return out;
}

/** JSON summary, handy for automated comparisons and bug reports. */
export function toJson(result: ConversionResult): string {
  return JSON.stringify(
    {
      width: SCREEN_W,
      height: SCREEN_H,
      cells: ROWS * COLS,
      stats: result.stats,
      attributes: Array.from(result.attr),
    },
    null,
    2,
  );
}
